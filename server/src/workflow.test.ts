test("summary pages retain drafts, submit once, cancel reminders and queue HOD delivery", async (t) => {
    const restore: Array<() => void> = [];
    const replace = (target: any, key: string, handler: any) => { const old = target[key]; target[key] = handler; restore.push(() => target[key] = old); };
    t.after(() => restore.reverse().forEach(f => f()));
    const row: any = { id: "completion", sessionId: "session", employeeId: "employee", summaryToken: "summary-token-test-12345678", status: "COMPLETED", summarySubmittedAt: null, employee: { name: "Test Employee", employeeId: "EMP1", status: "ACTIVE", hodEmail: "hod@example.test" }, session: { archivedAt: null, dateStart: new Date("2020-01-01T01:00Z"), dateEnd: new Date("2020-01-01T04:00Z"), course: { name: "Safety <script>alert(1)</script>" }, venue: "Room", trainerName: "Trainer", deliveryMethod: "Internal", notes: null } };
    const jobs: any[] = [{ kind: "FOLLOW_UP", status: "PENDING" }, { kind: "SUMMARY_REMINDER", status: "PENDING" }];
    let hodCreates = 0;
    replace(prisma.trainingCompletion, "findUnique", async ({ where }: any) => where.summaryToken === row.summaryToken ? row : null);
    const tx: any = { trainingCompletion: { updateMany: async ({ data }: any) => { if (row.summarySubmittedAt)
                return { count: 0 }; Object.assign(row, data); return { count: 1 }; } }, trainingEmailJob: { updateMany: async () => { jobs.forEach(j => j.status = "CANCELLED"); return { count: 2 }; }, upsert: async () => { hodCreates++; } } };
    replace(prisma, "$transaction", async (fn: any) => fn(tx));
    const server = createApp().listen(0, "127.0.0.1");
    await new Promise<void>(r => server.once("listening", r));
    t.after(() => new Promise<void>(r => server.close(() => r())));
    const address = server.address();
    assert.ok(address && typeof address !== "string");
    const root = `http://127.0.0.1:${address.port}/training/summary/`;
    assert.equal((await fetch(root + "invalid")).status, 400);
    const page = await fetch(root + row.summaryToken);
    assert.equal(page.status, 200);
    const html = await page.text();
    assert.match(html, /Safety &lt;script&gt;/);
    assert.doesNotMatch(html, /<script>alert/);
    assert.match(html, /Save draft/);
    const save = (body: unknown) => fetch(root + row.summaryToken, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
    assert.equal((await save({ submit: true })).status, 400);
    assert.equal((await save({ notes: "My notes", learning: "Learning draft" })).status, 200);
    assert.equal(row.summaryNotes, "My notes");
    assert.equal(row.summarySubmittedAt, null);
    assert.equal(hodCreates, 0);
    assert.equal(jobs[1].status, "PENDING");
    const files = [{ name: "notes.txt", data: "data:text/plain;base64,bm90ZXM=" }];
    assert.equal((await save({ learning: "Safe work", application: "Use the checklist", notes: "Full notes", attachments: files, submit: true })).status, 200);
    assert.ok(row.summarySubmittedAt);
    assert.equal(hodCreates, 1);
    assert.deepEqual(row.summaryAttachments, files);
    assert.ok(jobs.every(j => j.status === "CANCELLED"));
    assert.equal((await save({ learning: "Duplicate", application: "Duplicate", submit: true })).status, 200);
    assert.equal(hodCreates, 1);
    assert.equal(row.summaryLearning, "Safe work");
    row.session.archivedAt = new Date();
    assert.equal((await fetch(root + row.summaryToken)).status, 404);
});
test("one car reservation excludes competing employees and requires evidence before departure", async (t) => {
    const restore: Array<() => void> = [];
    const replace = (target: any, key: string, handler: any) => { const old = target[key]; target[key] = handler; restore.push(() => target[key] = old); };
    t.after(() => restore.reverse().forEach(f => f()));
    const car: any = { id: "car", status: "AVAILABLE", mileage: 100, serviceAt: 10000, serviceDueDate: null, archivedAt: null };
    let trip: any;
    const employee = { id: "employee", employeeId: "EMP1", name: "Test Driver", status: "ACTIVE" };
    replace(prisma.employee, "findFirst", async ({ where }: any) => where.employeeId.equals === "EMP1" ? employee : { ...employee, id: "other", employeeId: "EMP2", name: "Other Driver" });
    const tx: any = { $queryRaw: async () => [], vehicle: { updateMany: async () => { if (car.status !== "AVAILABLE")
                return { count: 0 }; car.status = "IN_USE"; return { count: 1 }; }, findUniqueOrThrow: async () => car, update: async ({ data }: any) => Object.assign(car, data) }, vehicleTrip: { findFirst: async ({ where }: any) => trip && trip.driverEmployeeId === where.driverEmployeeId ? trip : null, create: async ({ data }: any) => (trip = { id: "trip", ...data, vehicle: car }), findUniqueOrThrow: async () => trip, updateMany: async ({ where, data }: any) => { if (where.status !== trip.status)
                return { count: 0 }; Object.assign(trip, data); return { count: 1 }; } } };
    replace(prisma, "$transaction", async (fn: any) => fn(tx));
    const server = createApp().listen(0, "127.0.0.1");
    await new Promise<void>(r => server.once("listening", r));
    t.after(() => new Promise<void>(r => server.close(() => r())));
    const address = server.address();
    assert.ok(address && typeof address !== "string");
    const root = `http://127.0.0.1:${address.port}/api/vehicle-trips`;
    const post = (path: string, data: unknown) => fetch(root + path, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(data) });
    const identity = { driverEmployeeId: "EMP1", driverName: "Test Driver" };
    const reservation = { ...identity, vehicleId: "car", destination: "Office", purpose: "Meeting", expectedReturnAt: "2099-01-01T04:00:00Z" };
    assert.equal((await post("/reserve", { ...reservation, driverName: "Wrong Name" })).status, 400);
    assert.equal((await post("/reserve", reservation)).status, 201);
    assert.equal(trip.status, "AWAITING_DEPARTURE");
    assert.equal(trip.odometerPhotoBefore, undefined);
    assert.equal((await post("/reserve", { ...reservation, driverEmployeeId: "EMP2", driverName: "Other Driver" })).status, 409);
    assert.equal((await post("/trip/depart", identity)).status, 400);
    const evidence = { ...identity, odometerStart: 101, odometerPhotoBefore: "data:image/jpeg;base64,eA==", fuelBefore: 75, conditionBefore: "GOOD", checksBefore: { exterior: true, tyres: true, lights: true, documents: true } };
    assert.equal((await post("/trip/depart", { ...evidence, driverEmployeeId: "EMP2", driverName: "Other Driver" })).status, 403);
    assert.equal((await post("/trip/depart", { ...evidence, odometerStart: 99 })).status, 400);
    assert.equal((await post("/trip/depart", evidence)).status, 200);
    assert.equal(trip.status, "IN_PROGRESS");
    assert.equal(trip.mileageMismatch, true);
    assert.equal(car.mileage, 101);
    assert.equal((await post("/trip/depart", evidence)).status, 409);
    assert.equal((await post("/trip/cancel-reservation", identity)).status, 409);
});
